"""Lossless website-font partition. Requires fonttools[woff]==4.60.2 + brotli==1.2.0.

Run from the repository root. Retain the original OFL font and its license.
All original cmap entries, horizontal metrics and outlines are checked before
publishing; this never subsets from page copy, so CMS text keeps its coverage.
"""
from pathlib import Path
from fontTools import subset
from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
source = root / "public/fonts/APOWER-Han-Medium.woff"
original = TTFont(source, recalcTimestamp=False)
cmap = original.getBestCmap()
ui = {code for code in cmap if code < 0x2E80} | {ord(char) for char in "中文"}
groups = {"ui": ui, "body": set(cmap) - ui}


def ranges(codes):
    ordered = sorted(codes)
    runs = []
    start = last = ordered[0]
    for code in ordered[1:]:
        if code == last + 1:
            last = code
        else:
            runs.append((start, last))
            start = last = code
    runs.append((start, last))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)


css = ["/* Generated by scripts/split-han-font.py; same original Medium glyphs. */"]
seen = set()
original_glyphs = original.getGlyphSet()
for name, codes in groups.items():
    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.name_legacy = True
    engine = subset.Subsetter(options=options)
    engine.populate(unicodes=codes)
    engine.subset(font)
    font.flavor = "woff2"
    target = root / f"public/fonts/APOWER-Han-Medium-{name}.woff2"
    font.save(target)
    verified = TTFont(target)
    actual = verified.getBestCmap()
    assert set(actual) == codes
    assert not seen.intersection(codes)
    seen.update(codes)
    glyphs = verified.getGlyphSet()
    for code, glyph in actual.items():
        old = cmap[code]
        assert original["hmtx"].metrics[old] == verified["hmtx"].metrics[glyph]
        before, after = RecordingPen(), RecordingPen()
        original_glyphs[old].draw(before)
        glyphs[glyph].draw(after)
        assert before.value == after.value, f"Outline changed: U+{code:X}"
    css.append("@font-face{font-family:'APOWER Han';src:url('/fonts/" + target.name
               + "') format('woff2');font-style:normal;font-weight:500;"
               + "font-display:swap;unicode-range:" + ranges(codes) + "}")
    print(f"{name}: {len(codes)} identical glyphs, {target.stat().st_size} bytes")
assert seen == set(cmap)
(root / "app/han-fonts.css").write_text("\n".join(css) + "\n")
print("All original cmap entries, horizontal metrics and glyph outlines retained.")
